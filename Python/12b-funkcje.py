# funkcja, która wyświetla sumę z dodawania / funkcja ta przyjmuje argumenty a, b
def display_sum(a, b):
    print(a+b)

# funkcja, która zwraca sumę z dodawania / funkcja ta przyjmuje argumenty a, b
def return_sum(a, b):
    return a + b

# funkcja, która wyświetla wiadomość / funkcja ta nie przyjmuje żadnych argumentów
def print_message():
    print("to jest super wiadomość")


display_sum(2, 3)
return_sum(2, 3)
print_message()