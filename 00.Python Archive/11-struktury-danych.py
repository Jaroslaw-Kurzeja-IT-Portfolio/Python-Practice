# list - lista
    # można ją modyfikować, wartości mogą się duplikować
    # w nawiasach kwadratowych []

# tuple - krotka
    # nie da się jej modyfikować (nie można dodawać, usuwać elementów, jej sortować), tzw. struktura niemutowalna
    # w nawiasach okrąłych ()

# set - zbiór (3 cechy setu)
    # wartości elementów nie mogą być zduplikowane
    # elementu muszą być niemutowalne
    # elementy setu są nieuporządkowane
    # w nawiasach klamrowych {}

# dictionary - słownik
    # przypisuje wartości, struktura danych typu kluch : wartość