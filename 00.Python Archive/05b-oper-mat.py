a = 4
b = 2
c = 5

# operator modulo (%) - do sprawdzania reszty z dzielenia dwóch liczb

print(a % b)
print(c % b)

# operator potęgowania (**) - liczba przed operatorem do potęgi liczba po operatorze

print(a ** b)
print(c ** b)

# +=  ...dwa poniższe działania to to samo

a = a + 10
print(a)

a = 4

a += 10
print(a)